"""Chronological baseline training for the Chennai heatwave proxy task."""

from __future__ import annotations

import math
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import timedelta
from typing import Optional

import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, f1_score, precision_score, recall_score
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from src.feature_engineering import build_features
from src.heatwave_labels import assign_heatwave_proxy_labels


@dataclass(frozen=True)
class TrainingResult:
    """Fitted baseline and chronological holdout evaluation outputs.

    ``model`` is returned in memory for later inference; this module never
    writes it to disk. The confusion matrix is indexed by actual labels and
    columned by predicted labels, always in the order ``[0, 1]``.
    """

    model: Pipeline
    metrics: dict[str, float]
    confusion_matrix: pd.DataFrame
    training_rows: int
    validation_rows: int
    unknown_training_labels: int
    unknown_validation_labels: int
    boundary_censored_labels: int
    validation_positive_cases: int
    validation_note: Optional[str]
    training_start: pd.Timestamp
    training_end: pd.Timestamp
    validation_start: pd.Timestamp
    validation_end: pd.Timestamp
    feature_columns: tuple[str, ...]


def train_baseline_model(
    observations: pd.DataFrame,
    *,
    date_column: str = "date",
    max_temperature_column: str = "max_temp_c",
    departure_column: str = "departure_from_normal_c",
    label_column: str = "heatwave_proxy",
    min_temperature_column: Optional[str] = "min_temp_c",
    humidity_column: Optional[str] = "humidity",
    wind_speed_column: Optional[str] = "wind_speed",
    max_temperature_threshold_c: float = 37.0,
    departure_threshold_c: float = 4.5,
    minimum_consecutive_days: int = 2,
    lag_days: Sequence[int] = (1, 2, 3, 7),
    rolling_windows: Sequence[int] = (3, 7),
    train_fraction: float = 0.8,
    minimum_validation_positive_cases: int = 5,
) -> TrainingResult:
    """Train and evaluate a simple heatwave classifier using chronological data.

    Labels are generated by :func:`assign_heatwave_proxy_labels`, and
    predictors by :func:`build_features`.     The train/validation boundary is selected by chronological row position
    before rows with unknown labels are removed. Unknown labels are excluded
    from fitting/evaluation and counted separately; they are never converted
    to negatives. A qualifying persistence run that straddles the split is
    censored as unknown on both sides, preventing labels in either partition
    from depending on observations in the other partition without changing
    the label definition for retained rows.

    The estimator is a median-imputation, standardization, and balanced
    Logistic Regression pipeline. It is fitted only on known-labeled training
    rows; using a pipeline ensures preprocessing statistics are learned from
    the training partition and then applied unchanged to validation rows.
    Predictor input comes only from ``build_features`` (past-weather lags,
    past-only Tmax rolling summaries, and calendar features), never raw
    same-day weather or target/label columns.

    Args:
        observations: One row per daily observation. Required columns are the
            date, maximum temperature, and departure from normal. Optional
            minimum temperature, humidity, and wind columns are used when
            present.
        date_column: Name of the daily date column.
        max_temperature_column: Name of daily maximum temperature in °C.
        departure_column: Name of departure-from-normal temperature in °C;
            required by the existing proxy labeler.
        label_column: Name used for the generated proxy label. It is not
            included among predictors.
        min_temperature_column: Optional minimum-temperature column name.
        humidity_column: Optional humidity column name.
        wind_speed_column: Optional wind-speed column name.
        max_temperature_threshold_c: Inclusive Tmax threshold passed to the
            proxy labeler.
        departure_threshold_c: Inclusive departure threshold passed to the
            proxy labeler.
        minimum_consecutive_days: Persistence requirement passed to the proxy
            labeler.
        lag_days: Positive prior-calendar-day lags passed to the feature
            builder.
        rolling_windows: Positive prior-calendar-day window sizes passed to
            the feature builder.
        train_fraction: Fraction of chronologically sorted rows assigned to
            the training period; must be strictly between zero and one.
        minimum_validation_positive_cases: Minimum count used to flag when
            validation metrics may be unreliable due to few positive cases.

    Returns:
        A :class:`TrainingResult` containing the in-memory fitted pipeline,
        validation precision/recall/F1, a 2x2 confusion matrix, sample counts,
        split date ranges, and generated predictor names.

    Raises:
        TypeError: If ``observations`` is not a pandas DataFrame.
        ValueError: If the split or validation warning threshold is invalid,
            the dataset cannot produce both chronological partitions, no
            known-labeled rows remain in either partition, or the training
            partition does not contain both target classes.

    Notes:
        This function does not fetch weather observations and does not persist
        a model. Validation scores can be unstable or misleading when the
        validation partition contains very few positive cases; the returned
        ``validation_note`` calls this out.
    """
    if not isinstance(observations, pd.DataFrame):
        raise TypeError("observations must be a pandas DataFrame.")
    if (
        isinstance(train_fraction, bool)
        or not isinstance(train_fraction, (int, float))
        or not math.isfinite(train_fraction)
        or not 0.0 < train_fraction < 1.0
    ):
        raise ValueError("train_fraction must be a finite number strictly between 0 and 1.")
    if (
        isinstance(minimum_validation_positive_cases, bool)
        or not isinstance(minimum_validation_positive_cases, int)
        or minimum_validation_positive_cases < 1
    ):
        raise ValueError("minimum_validation_positive_cases must be a positive integer.")

    # A fresh unique index makes feature/label alignment positional and robust
    # even if the caller's DataFrame has duplicate index labels.
    source = observations.copy().reset_index(drop=True)
    labelled = assign_heatwave_proxy_labels(
        source,
        date_column=date_column,
        max_temperature_column=max_temperature_column,
        departure_column=departure_column,
        label_column=label_column,
        max_temperature_threshold_c=max_temperature_threshold_c,
        departure_threshold_c=departure_threshold_c,
        minimum_consecutive_days=minimum_consecutive_days,
    )
    features = build_features(
        source,
        date_column=date_column,
        max_temperature_column=max_temperature_column,
        min_temperature_column=min_temperature_column,
        humidity_column=humidity_column,
        wind_speed_column=wind_speed_column,
        lag_days=lag_days,
        rolling_windows=rolling_windows,
    )

    # build_features sorts by date while preserving the reset source index.
    # Align targets on that index and remove the date from the model matrix.
    targets = labelled.loc[features.index, label_column]
    feature_columns = tuple(column for column in features.columns if column != date_column)
    predictors = features.loc[:, feature_columns]

    split_at = int(len(features) * train_fraction)
    if split_at < 1 or split_at >= len(features):
        raise ValueError(
            "Not enough observations for the requested chronological "
            "train/validation split."
        )

    train_labels = targets.iloc[:split_at]
    validation_labels = targets.iloc[split_at:]
    boundary_censored_labels = 0
    if minimum_consecutive_days > 1:
        ordered_source = source.loc[features.index]
        maximum = pd.to_numeric(ordered_source[max_temperature_column], errors="raise")
        departure = pd.to_numeric(ordered_source[departure_column], errors="raise")
        known_conditions = maximum.notna() & departure.notna()
        qualifying = (
            maximum.ge(max_temperature_threshold_c)
            & departure.ge(departure_threshold_c)
            & known_conditions
        ).to_numpy(dtype=bool)
        ordered_dates = pd.DatetimeIndex(features[date_column])
        qualifying_run: list[int] = []

        def censor_split_spanning_run(run: list[int]) -> None:
            nonlocal boundary_censored_labels
            if run and run[0] < split_at <= run[-1]:
                targets.iloc[run] = pd.NA
                boundary_censored_labels += len(run)

        for position in range(len(features)):
            if not qualifying[position]:
                censor_split_spanning_run(qualifying_run)
                qualifying_run = []
                continue
            if (
                qualifying_run
                and ordered_dates[position] - ordered_dates[position - 1]
                != pd.Timedelta(days=1)
            ):
                censor_split_spanning_run(qualifying_run)
                qualifying_run = []
            qualifying_run.append(position)
        censor_split_spanning_run(qualifying_run)

        train_labels = targets.iloc[:split_at]
        validation_labels = targets.iloc[split_at:]

    train_known = train_labels.notna()
    validation_known = validation_labels.notna()
    unknown_training_labels = int((~train_known).sum())
    unknown_validation_labels = int((~validation_known).sum())
    if not train_known.any():
        raise ValueError("No known labels remain in the chronological training partition.")
    if not validation_known.any():
        raise ValueError("No known labels remain in the chronological validation partition.")

    x_train = predictors.iloc[:split_at].loc[train_known]
    y_train = train_labels.loc[train_known].astype("int8")
    x_validation = predictors.iloc[split_at:].loc[validation_known]
    y_validation = validation_labels.loc[validation_known].astype("int8")
    if y_train.nunique() < 2:
        raise ValueError(
            "The training partition must contain both negative and positive "
            "known labels to fit a binary classifier."
        )

    model = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median", keep_empty_features=True)),
            ("scaler", StandardScaler()),
            (
                "classifier",
                LogisticRegression(
                    class_weight="balanced",
                    max_iter=1000,
                    random_state=0,
                ),
            ),
        ]
    )
    # All learned preprocessing (medians and scaling statistics) is fit by
    # this pipeline using training rows only.
    model.fit(x_train, y_train)
    predictions = model.predict(x_validation)

    metrics = {
        "precision": float(
            precision_score(y_validation, predictions, zero_division=0)
        ),
        "recall": float(recall_score(y_validation, predictions, zero_division=0)),
        "f1": float(f1_score(y_validation, predictions, zero_division=0)),
    }
    matrix = confusion_matrix(y_validation, predictions, labels=[0, 1])
    confusion = pd.DataFrame(
        matrix,
        index=pd.Index([0, 1], name="actual"),
        columns=pd.Index([0, 1], name="predicted"),
    )
    validation_positive_cases = int(y_validation.sum())
    validation_note = None
    if validation_positive_cases < minimum_validation_positive_cases:
        validation_note = (
            "Validation metrics may be unreliable because the validation "
            f"partition has only {validation_positive_cases} positive case(s); "
            f"at least {minimum_validation_positive_cases} were requested for "
            "a more informative positive-case evaluation."
        )

    train_dates = features[date_column].iloc[:split_at]
    validation_dates = features[date_column].iloc[split_at:]
    return TrainingResult(
        model=model,
        metrics=metrics,
        confusion_matrix=confusion,
        training_rows=len(y_train),
        validation_rows=len(y_validation),
        unknown_training_labels=unknown_training_labels,
        unknown_validation_labels=unknown_validation_labels,
        boundary_censored_labels=boundary_censored_labels,
        validation_positive_cases=validation_positive_cases,
        validation_note=validation_note,
        training_start=pd.Timestamp(train_dates.iloc[0]),
        training_end=pd.Timestamp(train_dates.iloc[-1]),
        validation_start=pd.Timestamp(validation_dates.iloc[0]),
        validation_end=pd.Timestamp(validation_dates.iloc[-1]),
        feature_columns=feature_columns,
    )